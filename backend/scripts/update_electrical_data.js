// Function to parse CSV line preserving quoted values
function parseCSVLine(text) {
  const result = [];
  let cell = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '"') {
      inQuotes = !inQuotes;
    } else if (c === ',' && !inQuotes) {
      result.push(cell.trim());
      cell = "";
    } else {
      cell += c;
    }
  }
  result.push(cell.trim());
  return result;
}

function parseNum(val) {
  if (!val) return null;
  const match = val.replace(/,/g, "").match(/[-+]?\d*\.?\d+/);
  return match ? parseFloat(match[0]) : null;
}

function parseDate(val) {
  if (!val) return null;
  const d = new Date(val);
  return isNaN(d.getTime()) ? null : d;
}

async function main() {
  let cleanCSV = rawCSV;
  if (cleanCSV.includes("do same in electrical")) {
    cleanCSV = cleanCSV.replace("do same in electrical", "").trim();
  }

  const lines = cleanCSV.split("\n").map(l => l.trim()).filter(Boolean);
  const header = parseCSVLine(lines[0]);
  console.log("CSV Header:", header);

  const dataRows = lines.slice(1);
  console.log(`Parsing ${dataRows.length} CSV data lines...`);

  // Clear existing electrical orders, subItems, and items
  await prisma.electrical_orders.deleteMany({});
  await prisma.electrical_sub_items.deleteMany({});
  await prisma.electrical_items.deleteMany({});
  console.log("Cleared old electrical database tables.");

  let insertedCount = 0;

  for (const line of dataRows) {
    if (!line) continue;
    const cols = parseCSVLine(line);
    if (cols.length < 2) continue;

    const s_no = parseInt(cols[0], 10) || null;
    const item_name = cols[1] || "Uncategorized Electrical Item";
    const variant = cols[2] || "Standard";
    const dop = parseDate(cols[3]);
    const billNumber = cols[4] || null;
    const quantity = cols[5] || null;
    const unitRate = parseNum(cols[6]);
    const amount = parseNum(cols[7]);
    const issued = cols[8] || null;
    const balance = cols[9] || null;
    const dealerName = cols[10] || null;
    const remarks = cols[11] || null;

    // 1. Find or create electrical_items by name
    let item = await prisma.electrical_items.findUnique({
      where: { name: item_name }
    });

    if (!item) {
      item = await prisma.electrical_items.create({
        data: { name: item_name }
      });
    }

    // 2. Find or create electrical_sub_items by itemId + variant
    let subItem = await prisma.electrical_sub_items.findUnique({
      where: {
        itemId_variant: {
          itemId: item.id,
          variant: variant
        }
      }
    });

    if (!subItem) {
      subItem = await prisma.electrical_sub_items.create({
        data: {
          itemId: item.id,
          variant: variant
        }
      });
    }

    // 3. Create electrical_orders record
    await prisma.electrical_orders.create({
      data: {
        subItemId: subItem.id,
        dop,
        billNumber,
        quantity,
        unitRate,
        amount,
        issued,
        balance,
        dealerName,
        remarks,
        slp: s_no
      }
    });

    insertedCount++;
  }

  console.log(`Successfully updated and inserted ${insertedCount} electrical records into database!`);
}

main()
  .catch((e) => {
    console.error("Error updating electrical data:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
